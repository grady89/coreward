// THE NINE STONES — vault interiors (SPEC-GLYPHS.md §3).
//
// Hand-authored rooms folded into the carved stones. One mechanic each,
// introduced safe and then tested sharp; ~60–120s on a clean first clear.
// Authored as ASCII so a room can be reviewed in a diff and tuned in a
// text editor. Legend:
//
//   #  masonry (solid)          .  air, ambient worklight
//   d  air, DARK — no ambient refill, near-black until your lamp finds it
//   S  sconce (unlit)           @  entry (spawn + first checkpoint)
//   M  the master stone         X  unlight — touch it and you gutter out
//   A  light bridge, group A    b  light bridge, group B (A on while b off)
//   R  rime shelf — crumbles ~0.55s after you stand on it, regrows later
//   ^  air, gravity points UP   >  air, gravity points RIGHT
//   <  air, gravity points LEFT K  an unlit figure, standing (decor)
//
// Beams and wind live in the defs, not the maps — a sweep is an animation,
// not a tile.

export interface BeamDef {
  x: number; y: number;       // emitter, tile coords (y = row, downward)
  a0: number; a1: number;     // sweep endpoints, radians (0 = +x, -PI/2 = down)
  period: number;             // seconds for a full there-and-back
  phase: number;              // 0..1 offset
}

export interface WindDef {
  dir: -1 | 1;    // world-x direction the gust pushes
  calm: number;   // seconds of stillness
  gust: number;   // seconds of push
  force: number;  // accel while gusting
}

export interface VaultDef {
  glyph: string;          // GlyphDef id this room translates
  map: string[];          // rows, top to bottom, constant width
  /** worklight regrown from the air itself, per second (default 7) */
  ambient?: number;
  /** what a dead sconce takes out of you to light (the Famine) */
  sconceCost?: number;
  beams?: BeamDef[];
  wind?: WindDef;
}

